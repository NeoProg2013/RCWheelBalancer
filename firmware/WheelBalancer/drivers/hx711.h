/// ***************************************************************************
/// @file    hx711.h
/// @author  NeoProg
/// @brief   x6 HX711 parallel driver 
/// ***************************************************************************
#ifndef _HX711_H_
#define _HX711_H_
#include "core.h"


/// ***************************************************************************
/// @brief  HX711 driver initialization
/// ***************************************************************************
extern void hx711_init();

/// ***************************************************************************
/// @brief  HX711 power up/down
/// ***************************************************************************
extern void hx711_power_up();
extern void hx711_power_down();

/// ***************************************************************************
/// @brief  HX711 calibration
/// ***************************************************************************
extern bool hx711_calibration();

/// ***************************************************************************
/// @brief  HX711 process
/// ***************************************************************************
extern bool hx711_process();

/// ***************************************************************************
/// @brief  Check data ready
/// @return true - data ready, false - not
/// ***************************************************************************
extern bool hx711_is_data_ready();

/// ***************************************************************************
/// @brief  Process DI GPIO interrupt
/// @param  pr: EXTI->PR register value
/// ***************************************************************************
extern void hx711_process_irq(uint32_t pr);

/// ***************************************************************************
/// @brief  HX711 read values
/// @param  values: pointer to buffer for data
/// @return none
/// ***************************************************************************
extern void hx711_read(int16_t* data);


#endif // _HX711_H_
